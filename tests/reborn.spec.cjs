const {test,expect}=require('@playwright/test');
test.use({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
let errors=[];
test.beforeEach(async({page})=>{errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/reborn-preview/');await expect(page.locator('#dp-onboarding-roles [data-dp-role="student"]')).toBeVisible({timeout:15000})});
test.afterEach(()=>expect(errors,'JavaScript errors').toEqual([]));
test('Student schedule, countdown, settings',async({page})=>{
 await page.locator('[data-dp-role="student"]').click();
 await page.locator('#dp-group-search').fill('ЕІ-23-1');
 await page.locator('#dp-search-results button').first().click();
 await page.locator('#dp-setup-done').click();
 await page.locator('#dp-success-enter').click();
 await expect(page.locator('#nav button')).toHaveCount(4);
 await page.locator('#nav button[data-page="today"]').click();
 await expect(page.locator('#dp-live-lesson-clock')).toBeAttached();
 await page.locator('#nav button[data-page="schedule"]').click();
 await expect(page.locator('#screen')).toContainText('Розклад');
 await expect(page.locator('#dp40-share')).toBeVisible();
 await page.locator('#dp40-share').click();
 await expect(page.locator('#dp40-modal')).toBeVisible();
 await expect(page.locator('#dp40-bot')).toContainText('Telegram');
 await expect(page.locator('#dp40-modal img')).toHaveAttribute('src',/^blob:/);
 await page.locator('#dp40-modal .dp40-close').click();
 await page.locator('#nav button[data-page="notebook"]').click();
 await expect(page.locator('#dp-nb')).toBeVisible();
 await page.locator('#dp-nb [data-nb="new"]').click();
 await page.locator('#dp-nb-title').fill('Тестовий зошит');
 await page.locator('#dp-nb-body').fill('Перевірка автоматичного збереження');
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('depara_notebook_fresh_v1')||'[]')[0]?.body)).toBe('Перевірка автоматичного збереження');
 await page.locator('#dp-nb [data-nb="back"]').click();
 await expect(page.locator('#dp-nb')).toContainText('Тестовий зошит');
 await page.locator('#nav button[data-page="profile"]').click();
 await expect(page.locator('#screen')).toContainText('Налаштування');
});
test('Teacher timetable and three navigation tabs',async({page})=>{
 await page.locator('[data-dp-role="teacher"]').click();
 await page.locator('#dp-teacher-search').fill('Шту');
 await page.locator('#dp-teacher-search-results button').first().click();
 await page.locator('#dp-teacher-enter').click();
 const teacher=page.locator('#dp-teacher-app');
 await expect(teacher).toBeVisible();
 await expect(teacher.locator('.dp-t-nav button')).toHaveCount(3);
 await teacher.locator('.dp-t-nav [data-t-page="schedule"]').click();
 await expect(teacher.locator('#dp-t-refresh')).toBeVisible();
 await teacher.locator('#dp-t-next').click();
 await teacher.locator('[data-t-view="week"]').click();
});
